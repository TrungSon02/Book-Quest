-- Book Quest Database Schema (PostgreSQL DDL)
-- Covers all 8 domain groups (26 tables) from the Book Quest ER specification.

-- ============================================================================
-- Group 2 (Core Catalog Referenced by Group 1): Genres & Books
-- ============================================================================

CREATE TABLE genres (
    genre_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE books (
    book_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name      VARCHAR(255) NOT NULL,
    title            VARCHAR(255) NOT NULL,
    description      TEXT NOT NULL,
    english_level    VARCHAR(10) NOT NULL CHECK (english_level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    word_count       INT NOT NULL CHECK (word_count >= 0),
    cover_image_url  TEXT NOT NULL,
    publication_date DATE NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- Group 1. User Management
-- ============================================================================

CREATE TABLE users (
    user_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           VARCHAR(100) NOT NULL,
    email              VARCHAR(255) NOT NULL UNIQUE,
    password_hash      VARCHAR(255) NOT NULL,
    english_level      VARCHAR(10) NOT NULL CHECK (english_level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    timezone           VARCHAR(100) NOT NULL DEFAULT 'UTC',
    daily_reading_goal INT NOT NULL DEFAULT 15 CHECK (daily_reading_goal > 0),
    preferred_language VARCHAR(20) NOT NULL DEFAULT 'en',
    account_role       VARCHAR(30) NOT NULL DEFAULT 'learner' CHECK (account_role IN ('learner', 'admin')),
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_genres (
    user_id  BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES genres(genre_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, genre_id)
);

CREATE TABLE user_books (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, book_id)
);

-- ============================================================================
-- Group 2. Book Catalog (Junction, Chapters, Files)
-- ============================================================================

CREATE TABLE book_genres (
    book_id  BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES genres(genre_id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, genre_id)
);

CREATE TABLE chapters (
    chapter_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id          BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    chapter_number   INT NOT NULL CHECK (chapter_number > 0),
    title            VARCHAR(255) NOT NULL,
    word_count       INT NOT NULL CHECK (word_count >= 0),
    epub_chapter_ref VARCHAR(255) NOT NULL,
    CONSTRAINT uq_chapters_book_number UNIQUE (book_id, chapter_number)
);

CREATE TABLE book_files (
    file_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    format      VARCHAR(20) NOT NULL CHECK (format IN ('EPUB', 'PDF')),
    file_url    TEXT NOT NULL,
    file_size   BIGINT NOT NULL CHECK (file_size >= 0),
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- Group 3. Reading System
-- ============================================================================

CREATE TABLE user_library (
    user_library_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    book_id         BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    status          VARCHAR(30) NOT NULL DEFAULT 'WANT_TO_READ' CHECK (status IN ('WANT_TO_READ', 'READING', 'COMPLETED')),
    is_favorite     BOOLEAN NOT NULL DEFAULT FALSE,
    added_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_library_user_book UNIQUE (user_id, book_id)
);

CREATE TABLE reading_sessions (
    session_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    book_id          BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    started_at       TIMESTAMP NOT NULL,
    ended_at         TIMESTAMP,
    duration_seconds INT NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    words_read       INT NOT NULL DEFAULT 0 CHECK (words_read >= 0),
    start_position   TEXT NOT NULL,
    end_position     TEXT
);

CREATE TABLE reading_progress (
    progress_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    book_id          BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    chapter_id       BIGINT REFERENCES chapters(chapter_id) ON DELETE SET NULL,
    current_position TEXT NOT NULL,
    progress_percent DECIMAL(5, 2) NOT NULL DEFAULT 0.00 CHECK (progress_percent >= 0 AND progress_percent <= 100),
    last_read_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reading_progress_user_book UNIQUE (user_id, book_id)
);

-- ============================================================================
-- Group 4. Quiz System
-- ============================================================================

CREATE TABLE quizzes (
    quiz_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id           BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    chapter_id        BIGINT REFERENCES chapters(chapter_id) ON DELETE SET NULL,
    session_id        BIGINT REFERENCES reading_sessions(session_id) ON DELETE SET NULL,
    quiz_type         VARCHAR(20) NOT NULL CHECK (quiz_type IN ('BOOK', 'CHAPTER', 'SESSION')),
    generation_source VARCHAR(20) NOT NULL CHECK (generation_source IN ('AI', 'ADMIN')),
    generation_model  VARCHAR(100),
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE questions (
    question_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       BIGINT NOT NULL REFERENCES quizzes(quiz_id) ON DELETE CASCADE,
    question_text TEXT NOT NULL,
    question_type VARCHAR(30) NOT NULL DEFAULT 'MULTIPLE_CHOICE',
    explanation   TEXT
);

CREATE TABLE question_options (
    option_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    option_text TEXT NOT NULL,
    is_correct  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE quiz_attempts (
    attempt_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    quiz_id         BIGINT NOT NULL REFERENCES quizzes(quiz_id) ON DELETE CASCADE,
    score           DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    correct_answers INT NOT NULL DEFAULT 0 CHECK (correct_answers >= 0),
    total_questions INT NOT NULL CHECK (total_questions > 0),
    started_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at    TIMESTAMP
);

CREATE TABLE user_answers (
    answer_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id          BIGINT NOT NULL REFERENCES quiz_attempts(attempt_id) ON DELETE CASCADE,
    question_id         BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    selected_option_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    answer_text         TEXT,
    is_correct          BOOLEAN NOT NULL DEFAULT FALSE
);

-- ============================================================================
-- Group 5. Reading Habit System
-- ============================================================================

CREATE TABLE habit_programs (
    program_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_name  VARCHAR(255) NOT NULL,
    duration_days INT NOT NULL CHECK (duration_days > 0),
    description   TEXT NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE habit_program_days (
    program_day_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id     BIGINT NOT NULL REFERENCES habit_programs(program_id) ON DELETE CASCADE,
    day_number     INT NOT NULL CHECK (day_number > 0),
    goal_metric    VARCHAR(20) NOT NULL CHECK (goal_metric IN ('PAGES', 'WORDS', 'MINUTES')),
    target_value   INT NOT NULL CHECK (target_value > 0),
    CONSTRAINT uq_habit_program_days_program_day UNIQUE (program_id, day_number)
);

CREATE TABLE user_habit_enrollments (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    program_id    BIGINT NOT NULL REFERENCES habit_programs(program_id) ON DELETE CASCADE,
    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL,
    status        VARCHAR(30) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'COMPLETED', 'DROPPED'))
);

CREATE TABLE daily_reading_activity (
    activity_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    activity_date   DATE NOT NULL,
    words_read      INT NOT NULL DEFAULT 0 CHECK (words_read >= 0),
    reading_seconds INT NOT NULL DEFAULT 0 CHECK (reading_seconds >= 0),
    pages_read      INT NOT NULL DEFAULT 0 CHECK (pages_read >= 0),
    goal_completed  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_daily_reading_activity_user_date UNIQUE (user_id, activity_date)
);

-- ============================================================================
-- Group 6. Gamification System
-- ============================================================================

CREATE TABLE coin_transactions (
    transaction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    amount           INT NOT NULL,
    transaction_type VARCHAR(50) NOT NULL,
    description      VARCHAR(255) NOT NULL,
    idempotency_key  VARCHAR(150) NOT NULL UNIQUE,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rewards (
    reward_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward_name  VARCHAR(255) NOT NULL,
    reward_type  VARCHAR(50) NOT NULL,
    coin_price   INT NOT NULL CHECK (coin_price > 0),
    description  TEXT NOT NULL,
    image_url    TEXT NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE reward_redemptions (
    redemption_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reward_id     BIGINT NOT NULL REFERENCES rewards(reward_id) ON DELETE RESTRICT,
    coins_spent   INT NOT NULL CHECK (coins_spent > 0),
    redeemed_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- Group 7. AI Recommendation System
-- ============================================================================

CREATE TABLE recommendation_runs (
    run_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    model_name          VARCHAR(100) NOT NULL,
    recommendation_type VARCHAR(50) NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recommendation_items (
    item_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                BIGINT NOT NULL REFERENCES recommendation_runs(run_id) ON DELETE CASCADE,
    book_id               BIGINT NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    rank                  INT NOT NULL CHECK (rank > 0),
    relevance_score       DECIMAL(5, 4) NOT NULL CHECK (relevance_score >= 0 AND relevance_score <= 1),
    recommendation_reason TEXT NOT NULL,
    user_feedback         VARCHAR(30)
);

-- ============================================================================
-- Group 8. Reading Reminders
-- ============================================================================

CREATE TABLE reading_reminders (
    reminder_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reminder_time TIME NOT NULL,
    days_of_week  SMALLINT[] NOT NULL,
    is_enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

